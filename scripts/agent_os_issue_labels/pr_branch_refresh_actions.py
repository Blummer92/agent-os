"""Finite GitHub Actions ingress contract for governed PR refresh (#1807).

This module classifies only the owner-authored operation identity needed to route
an issue-comment event toward the existing #1187/#1365/#1381 refresh stack. It
never grants branch-refresh authority and never accepts shell text, repository,
branch, refspec, path, credential, or authorization inputs from the comment.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Mapping

_REPOSITORY = "Blummer92/agent-os"
_REPOSITORY_ID = 1289370915
_OWNER_LOGIN = "Blummer92"
_OWNER_ID = 32861845
_WORKFLOW_REF = (
    "Blummer92/agent-os/.github/workflows/"
    "agent-os-governed-invocation.yml@refs/heads/main"
)
_TRIGGER = re.compile(r"^/agent-os refresh-pr (?P<pr>[1-9][0-9]*)$")
_CLAUDE_CODE_ATTRIBUTION_FOOTER = (
    "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
)
# Footer parity with approval_source.py (#3730): the bare form is retained
# for triggers already posted with it; a trigger rejected here for a legacy
# footer would strand the refresh the owner already requested.
_CLAUDE_CODE_FOOTERS = (
    _CLAUDE_CODE_ATTRIBUTION_FOOTER,
    "\n\n---\n_Generated by [Claude Code](https://claude.ai)_",
)


def _canonical_trigger_body(body: str) -> str:
    """Strip exactly one known connector attribution footer, and nothing else."""
    for footer in _CLAUDE_CODE_FOOTERS:
        if body.endswith(footer):
            candidate = body[: -len(footer)]
            if not any(known in candidate for known in _CLAUDE_CODE_FOOTERS):
                return candidate
    return body


@dataclass(frozen=True, slots=True)
class BranchRefreshActionsTrigger:
    status: str
    reason: str
    pr_number: int | None
    repository: str
    # Triggering issue-comment id when the event payload carries a valid one;
    # None when unavailable. Carried only as correlation evidence, never as
    # authority: a comment id alone authorizes nothing.
    trigger_comment_id: int | None = None
    side_effects_performed: bool = field(default=False, init=False)
    branch_refresh_authorized: bool = field(default=False, init=False)
    label_write_authorized: bool = field(default=False, init=False)
    merge_authorized: bool = field(default=False, init=False)
    issue_closure_authorized: bool = field(default=False, init=False)


def classify_branch_refresh_actions_trigger(
    event: Mapping[str, object],
    *,
    repository: str,
    repository_id: int,
    ref: str,
    workflow_ref: str,
    run_attempt: int,
) -> BranchRefreshActionsTrigger:
    """Classify one fixed refresh operation without manufacturing authority."""
    # Correlation only: extract the triggering comment id before any
    # rejection, so even a blocked trigger can be correlated in logs.
    # A malformed id is discarded (None), never repaired or trusted.
    raw_comment = event.get("comment")
    trigger_comment_id = None
    if isinstance(raw_comment, Mapping):
        comment_id = raw_comment.get("id")
        if type(comment_id) is int and comment_id >= 1:
            trigger_comment_id = comment_id

    if repository != _REPOSITORY or repository_id != _REPOSITORY_ID:
        return _blocked(repository, "repository-not-allowed", trigger_comment_id=trigger_comment_id)
    if ref != "refs/heads/main" or workflow_ref != _WORKFLOW_REF:
        return _blocked(repository, "workflow-source-not-canonical", trigger_comment_id=trigger_comment_id)
    if run_attempt != 1:
        return _blocked(repository, "rerun-not-allowed", trigger_comment_id=trigger_comment_id)
    if event.get("action") != "created":
        return _blocked(repository, "event-action-not-allowed", trigger_comment_id=trigger_comment_id)

    issue = event.get("issue")
    comment = event.get("comment")
    repo = event.get("repository")
    if not isinstance(issue, Mapping) or not isinstance(comment, Mapping) or not isinstance(repo, Mapping):
        return _blocked(repository, "event-shape-invalid", trigger_comment_id=trigger_comment_id)
    if issue.get("pull_request") is not None:
        return _blocked(repository, "pr-comment-not-allowed", trigger_comment_id=trigger_comment_id)
    if repo.get("id") != _REPOSITORY_ID or repo.get("full_name") != _REPOSITORY:
        return _blocked(repository, "event-repository-mismatch", trigger_comment_id=trigger_comment_id)

    actor = comment.get("user")
    body = comment.get("body")
    if not isinstance(actor, Mapping) or actor.get("login") != _OWNER_LOGIN or actor.get("id") != _OWNER_ID:
        return _blocked(repository, "actor-not-allowed", trigger_comment_id=trigger_comment_id)
    if not isinstance(body, str):
        return _blocked(repository, "comment-body-invalid", trigger_comment_id=trigger_comment_id)
    match = _TRIGGER.fullmatch(_canonical_trigger_body(body))
    if match is None:
        return _blocked(repository, "operation-not-requested", trigger_comment_id=trigger_comment_id)

    pr_number = int(match.group("pr"))
    return BranchRefreshActionsTrigger(
        status="accepted",
        reason="finite-refresh-operation-requested",
        pr_number=pr_number,
        repository=repository,
        trigger_comment_id=trigger_comment_id,
    )


def classify_event_file(
    event_path: str,
    *,
    repository: str,
    repository_id: int,
    ref: str,
    workflow_ref: str,
    run_attempt: int,
) -> BranchRefreshActionsTrigger:
    path = Path(event_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("event payload must be an object")
    return classify_branch_refresh_actions_trigger(
        payload,
        repository=repository,
        repository_id=repository_id,
        ref=ref,
        workflow_ref=workflow_ref,
        run_attempt=run_attempt,
    )


def _blocked(repository: str, reason: str, *, trigger_comment_id: int | None = None) -> BranchRefreshActionsTrigger:
    return BranchRefreshActionsTrigger(
        status="blocked",
        reason=reason,
        pr_number=None,
        repository=repository,
        trigger_comment_id=trigger_comment_id,
    )
