"""Trusted GitHub-conversation source for approval records (#3463).

The source is intentionally read-only. GitHub transport is injected; only exact
repository-owner-authored machine records from a complete PR conversation are
accepted. This mirrors merge_authorization_source.py: the codecs already exist
(reconstruct_approval_record), only the transport convention and source reader
were missing.

A merge-admission consumer uses this to obtain the canonical owner approval
that a merge authorization record references (approval_id / approval_revision
in the authorization binding). Applicability and projection artifacts are
recomputed canonically by the authorization evaluator, not trusted from the
conversation, so this source carries approval records only.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Literal, Protocol, runtime_checkable

from .approval_records import (
    ApprovalRecord,
    ApprovalState,
    reconstruct_approval_record,
    serialize_approval_record,
)

APPROVAL_MARKER = "agent-os-approval/v1"
MAX_COMMENTS = 512
MAX_COMMENT_BYTES = 32 * 1024
MAX_TOTAL_COMMENT_BYTES = 256 * 1024
_CLAUDE_CODE_ATTRIBUTION_FOOTER = (
    "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
)


def _canonical_comment_body(body: str) -> str:
    """Strip exactly one known connector attribution footer, and nothing else.

    Mirrors merge_authorization_source._canonical_comment_body: the footer is
    tolerated only when it is the single trailing occurrence. Anything else
    still fails the exact-shape check below.
    """
    if body.endswith(_CLAUDE_CODE_ATTRIBUTION_FOOTER):
        candidate = body[: -len(_CLAUDE_CODE_ATTRIBUTION_FOOTER)]
        if _CLAUDE_CODE_ATTRIBUTION_FOOTER not in candidate:
            return candidate
    return body


class ApprovalSourceStatus(str, Enum):
    CURRENT = "current"
    BLOCKED = "blocked"
    STALE = "stale"
    NEEDS_DECISION = "needs-decision"


@dataclass(frozen=True, slots=True)
class ApprovalCommentSnapshot:
    comment_id: int
    author_login: str
    created_at: str
    body: str


@dataclass(frozen=True, slots=True)
class ApprovalSourceSnapshot:
    repository: str
    pr_number: int
    owner_login: str
    owner_type: str
    comments_complete: bool
    comments: tuple[ApprovalCommentSnapshot, ...]


@runtime_checkable
class ApprovalSourceTransport(Protocol):
    def read_approval_source(
        self, repository: str, pr_number: int
    ) -> ApprovalSourceSnapshot: ...


@dataclass(frozen=True, slots=True)
class ApprovalSourceResult:
    status: ApprovalSourceStatus
    reason_codes: tuple[str, ...]
    records: tuple[ApprovalRecord, ...]
    source_comment_ids: tuple[int, ...]
    side_effects_performed: Literal[False] = field(default=False, init=False)


def serialize_approval_comment(record: ApprovalRecord) -> str:
    payload = serialize_approval_record(record).decode("utf-8").rstrip("\n")
    return APPROVAL_MARKER + "\n" + payload


def reacquire_approval_source(
    *,
    transport: ApprovalSourceTransport,
    repository: str,
    pr_number: int,
    expected_approval_id: str | None = None,
) -> ApprovalSourceResult:
    if not isinstance(transport, ApprovalSourceTransport):
        raise TypeError("transport does not satisfy ApprovalSourceTransport")
    try:
        snapshot = transport.read_approval_source(repository, pr_number)
    except Exception:
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.unavailable",), (), (),
        )
    if (
        type(snapshot) is not ApprovalSourceSnapshot
        or snapshot.repository.casefold() != repository.casefold()
        or snapshot.pr_number != pr_number
    ):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.identity-mismatch",), (), (),
        )
    if snapshot.owner_type != "User" or not snapshot.comments_complete:
        reason = "source.owner-unsupported" if snapshot.owner_type != "User" else "source.incomplete"
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION, (reason,), (), (),
        )
    if len(snapshot.comments) > MAX_COMMENTS or sum(
        len(item.body.encode("utf-8")) for item in snapshot.comments
    ) > MAX_TOTAL_COMMENT_BYTES:
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.outside-bounds",), (), (),
        )
    ids = [item.comment_id for item in snapshot.comments]
    if len(ids) != len(set(ids)):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.ambiguous",), (), (),
        )

    records: list[ApprovalRecord] = []
    source_ids: list[int] = []
    try:
        for item in sorted(snapshot.comments, key=lambda value: (value.created_at, value.comment_id)):
            if (
                item.author_login.casefold() != snapshot.owner_login.casefold()
                or not item.body.startswith(APPROVAL_MARKER + "\n")
            ):
                continue
            if len(item.body.encode("utf-8")) > MAX_COMMENT_BYTES:
                raise ValueError("trusted comment exceeds bounds")
            payload = _canonical_comment_body(item.body)[len(APPROVAL_MARKER) + 1 :]
            if "\n" in payload:
                raise ValueError("trusted approval must contain exactly two lines")
            record = reconstruct_approval_record(payload)
            if record.binding.repository.casefold() != repository.casefold():
                raise ValueError("trusted approval repository mismatch")
            records.append(record)
            source_ids.append(item.comment_id)
    except (TypeError, ValueError):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.trusted-record-malformed",), (), (),
        )

    if expected_approval_id is not None:
        records = [item for item in records if item.approval_id == expected_approval_id]
    if not records:
        return ApprovalSourceResult(
            ApprovalSourceStatus.BLOCKED,
            ("approval.absent",), (), tuple(source_ids),
        )

    by_id: dict[str, ApprovalRecord] = {}
    for record in records:
        prior = by_id.get(record.approval_id)
        if prior is None or record.revision_number > prior.revision_number:
            by_id[record.approval_id] = record
        elif record.revision_number == prior.revision_number and record != prior:
            return ApprovalSourceResult(
                ApprovalSourceStatus.NEEDS_DECISION,
                ("approval.conflicting-revision",), (), tuple(source_ids),
            )

    current = tuple(
        record for record in by_id.values()
        if record.state is ApprovalState.APPROVED
    )
    if not current:
        return ApprovalSourceResult(
            ApprovalSourceStatus.STALE,
            ("approval.consumed-or-not-current",), (), tuple(source_ids),
        )
    return ApprovalSourceResult(
        ApprovalSourceStatus.CURRENT,
        ("current",), current, tuple(source_ids),
    )
