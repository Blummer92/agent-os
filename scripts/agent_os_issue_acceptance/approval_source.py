"""Trusted GitHub-conversation source for approval artifacts (#2340).

The source is intentionally read-only. GitHub transport is injected; only exact
repository-owner-authored machine records from a complete PR conversation are
accepted. This mirrors ``merge_authorization_source.py`` for the three approval
artifacts whose canonical codecs already exist:

- ``agent-os-approval/v1``                        -> ApprovalRecord
- ``agent-os-approval-applicability/v1``          -> ApprovalApplicabilityResult
- ``agent-os-approved-execution-projection/v1``   -> ApprovedExecutionProjection

A CURRENT result requires a coherent triple: the applicability result and the
projection must name the same approval id/revision as an APPROVED approval
record, the applicability result must be applicable, and the projection must
be complete. Anything else fails closed.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Literal, Protocol, runtime_checkable

from .approval_records import (
    ApprovalApplicabilityResult,
    ApprovalRecord,
    ApprovalState,
    reconstruct_approval_applicability_result,
    reconstruct_approval_record,
    serialize_approval_applicability_result,
    serialize_approval_record,
)
from .approved_execution_projection import (
    ApprovedExecutionProjection,
    reconstruct_approved_execution_projection,
    serialize_approved_execution_projection,
)

APPROVAL_MARKER = "agent-os-approval/v1"
APPLICABILITY_MARKER = "agent-os-approval-applicability/v1"
PROJECTION_MARKER = "agent-os-approved-execution-projection/v1"
# The footer Claude Code actually appends links to /code; the bare form is
# retained for records already posted with it.
_CLAUDE_CODE_FOOTERS = (
    "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
    "\n\n---\n_Generated by [Claude Code](https://claude.ai)_",
)
MAX_COMMENTS = 512
MAX_COMMENT_BYTES = 32 * 1024
MAX_TOTAL_COMMENT_BYTES = 256 * 1024


def _canonical_comment_body(body: str) -> str:
    """Strip exactly one known connector attribution footer, and nothing else.

    Mirrors merge_authorization_source._canonical_comment_body: the footer is
    tolerated only when it is the single trailing occurrence. Anything else
    still fails the exact-shape check below.
    """
    for footer in _CLAUDE_CODE_FOOTERS:
        if body.endswith(footer):
            candidate = body[: -len(footer)]
            if not any(known in candidate for known in _CLAUDE_CODE_FOOTERS):
                return candidate
    return body


class ApprovalSourceStatus(str, Enum):
    CURRENT = "current"
    BLOCKED = "blocked"
    STALE = "stale"
    NEEDS_DECISION = "needs-decision"


@dataclass(frozen=True, slots=True)
class ApprovalCommentSnapshot:
    comment_id: int
    author_login: str
    created_at: str
    body: str


@dataclass(frozen=True, slots=True)
class ApprovalSourceSnapshot:
    repository: str
    pr_number: int
    owner_login: str
    owner_type: str
    comments_complete: bool
    comments: tuple[ApprovalCommentSnapshot, ...]


@runtime_checkable
class ApprovalSourceTransport(Protocol):
    def read_approval_source(
        self, repository: str, pr_number: int
    ) -> ApprovalSourceSnapshot: ...


@dataclass(frozen=True, slots=True)
class ApprovalSourceResult:
    status: ApprovalSourceStatus
    reason_codes: tuple[str, ...]
    approval: ApprovalRecord | None
    applicability: ApprovalApplicabilityResult | None
    projection: ApprovedExecutionProjection | None
    source_comment_ids: tuple[int, ...]
    side_effects_performed: Literal[False] = field(default=False, init=False)


def serialize_approval_comment(marker: str, payload: bytes) -> str:
    """Render one owner-postable approval artifact comment body."""
    text = payload.decode("utf-8").rstrip("\n")
    if "\n" in text:
        raise ValueError("approval artifact payload must be a single line")
    if marker not in (APPROVAL_MARKER, APPLICABILITY_MARKER, PROJECTION_MARKER):
        raise ValueError("unknown approval artifact marker")
    return marker + "\n" + text


def _payload(marker: str, body: str) -> str | None:
    text = _canonical_comment_body(body)
    if not text.startswith(marker + "\n"):
        return None
    payload = text[len(marker) + 1 :]
    if "\n" in payload:
        raise ValueError("trusted approval artifact must contain exactly two lines")
    return payload


def reacquire_approval_source(
    *,
    transport: ApprovalSourceTransport,
    repository: str,
    pr_number: int,
    expected_approval_id: str | None = None,
) -> ApprovalSourceResult:
    if not isinstance(transport, ApprovalSourceTransport):
        raise TypeError("transport does not satisfy ApprovalSourceTransport")
    try:
        snapshot = transport.read_approval_source(repository, pr_number)
    except Exception:
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.unavailable",), None, None, None, (),
        )
    if (
        type(snapshot) is not ApprovalSourceSnapshot
        or snapshot.repository.casefold() != repository.casefold()
        or snapshot.pr_number != pr_number
    ):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.identity-mismatch",), None, None, None, (),
        )
    if snapshot.owner_type != "User" or not snapshot.comments_complete:
        reason = "source.owner-unsupported" if snapshot.owner_type != "User" else "source.incomplete"
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION, (reason,), None, None, None, (),
        )
    if len(snapshot.comments) > MAX_COMMENTS or sum(
        len(item.body.encode("utf-8")) for item in snapshot.comments
    ) > MAX_TOTAL_COMMENT_BYTES:
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.outside-bounds",), None, None, None, (),
        )
    ids = [item.comment_id for item in snapshot.comments]
    if len(ids) != len(set(ids)):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.ambiguous",), None, None, None, (),
        )

    approvals: dict[str, ApprovalRecord] = {}
    applicabilities: dict[str, ApprovalApplicabilityResult] = {}
    projections: dict[str, ApprovedExecutionProjection] = {}
    source_ids: list[int] = []
    try:
        for item in sorted(snapshot.comments, key=lambda value: (value.created_at, value.comment_id)):
            if item.author_login.casefold() != snapshot.owner_login.casefold():
                continue
            if len(item.body.encode("utf-8")) > MAX_COMMENT_BYTES:
                raise ValueError("trusted comment exceeds bounds")
            handled = False
            for marker, store, rebuild in (
                (APPROVAL_MARKER, approvals, reconstruct_approval_record),
                (APPLICABILITY_MARKER, applicabilities, reconstruct_approval_applicability_result),
                (PROJECTION_MARKER, projections, reconstruct_approved_execution_projection),
            ):
                payload = _payload(marker, item.body)
                if payload is None:
                    continue
                handled = True
                record = rebuild(payload)
                key = _artifact_key(marker, record)
                prior = store.get(key)
                if prior is not None and record != prior:
                    raise ValueError("conflicting trusted approval artifact")
                store[key] = record
                source_ids.append(item.comment_id)
                break
            _ = handled
    except (TypeError, ValueError):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("source.trusted-record-malformed",), None, None, None, (),
        )

    if expected_approval_id is not None:
        approvals = {
            key: record for key, record in approvals.items()
            if record.approval_id == expected_approval_id
        }
    if not approvals:
        return ApprovalSourceResult(
            ApprovalSourceStatus.BLOCKED,
            ("approval.absent",), None, None, None, tuple(source_ids),
        )
    if len(approvals) > 1:
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("approval.ambiguous",), None, None, None, tuple(source_ids),
        )
    approval = next(iter(approvals.values()))
    if approval.state is not ApprovalState.APPROVED:
        return ApprovalSourceResult(
            ApprovalSourceStatus.STALE,
            ("approval.not-approved",), None, None, None, tuple(source_ids),
        )
    applicability = applicabilities.get(approval.approval_id)
    projection = projections.get(approval.approval_id)
    if applicability is None or projection is None:
        missing = [
            name for name, value in (
                ("applicability", applicability), ("projection", projection),
            ) if value is None
        ]
        return ApprovalSourceResult(
            ApprovalSourceStatus.BLOCKED,
            tuple(f"approval.{name}-absent" for name in missing),
            None, None, None, tuple(source_ids),
        )
    if (
        applicability.approval_revision != approval.approval_revision
        or projection.approval_revision != approval.approval_revision
        or projection.approval_id != approval.approval_id
        or projection.approval_state != "approved"
    ):
        return ApprovalSourceResult(
            ApprovalSourceStatus.NEEDS_DECISION,
            ("approval.binding-mismatch",), None, None, None, tuple(source_ids),
        )
    if applicability.status != "applicable" or not applicability.approval_applicable:
        return ApprovalSourceResult(
            ApprovalSourceStatus.STALE,
            ("approval.not-applicable",), None, None, None, tuple(source_ids),
        )
    return ApprovalSourceResult(
        ApprovalSourceStatus.CURRENT,
        ("current",), approval, applicability, projection, tuple(source_ids),
    )


def _artifact_key(marker: str, record: object) -> str:
    if marker == APPROVAL_MARKER:
        record = _verified_approval(record)
        return record.approval_id
    return _verified_approval_artifact(record).approval_id


def _verified_approval(record: object) -> ApprovalRecord:
    if not isinstance(record, ApprovalRecord):
        raise TypeError("approval artifact must be an ApprovalRecord")
    return record


def _verified_approval_artifact(
    record: object,
) -> ApprovalApplicabilityResult | ApprovedExecutionProjection:
    if not isinstance(
        record, (ApprovalApplicabilityResult, ApprovedExecutionProjection)
    ):
        raise TypeError("approval artifact has an unexpected type")
    return record
