def test_validate_all_receipt_function_writes_bound_receipt(tmp_path: Path) -> None:
    """Extract write_subtest_receipt (plus the junit path helpers it
    calls) from scripts/validate-all.sh as committed and run it: the
    wiring must write the receipt the extractor builds, and do nothing
    when CI_JUNIT_DIR is unset."""
    import re

    repo_root = Path(__file__).resolve().parents[1]
    script = (repo_root / "scripts/validate-all.sh").read_text(encoding="utf-8")
    assert "write_subtest_receipt" in script
    assert "CI_JUNIT_RUN_ID" in script and "CI_JUNIT_HEAD_SHA" in script

    def _fn(name: str) -> str:
        match = re.search(rf"^{name}\(\) \{{$(.*?)^\}}", script, re.MULTILINE | re.DOTALL)
        assert match is not None, name
        return f"{name}() {{\n{match.group(1)}}}\n"

    harness = "".join(
        _fn(name) for name in ("junit_key", "junit_path_for", "suite_junit_path_for", "write_subtest_receipt")
    )
    junit_dir = tmp_path / "junit"
    junit_dir.mkdir()
    xml, output = _genuine_pass_fixture(tmp_path)
    (junit_dir / "root.xml").write_bytes(xml)
    output_file = tmp_path / "pytest-output.txt"
    output_file.write_text(output, encoding="utf-8")
    script_text = harness + (
        f'CI_JUNIT_DIR="{junit_dir}" CI_JUNIT_RUN_ID="{RUN_ID}" CI_JUNIT_RUN_ATTEMPT="1" '
        f'CI_JUNIT_HEAD_SHA="{SOURCE_HEAD}" PYTHON_BIN="{sys.executable}" '
        f'write_subtest_receipt root "{output_file}"\n'
    )
    proc = subprocess.run(["bash", "-c", script_text], capture_output=True, text=True, cwd=repo_root)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    receipt_path = junit_dir / "junit-subtest-receipt-root.json"
    assert receipt_path.is_file()
    receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
    assert receipt["subtests_passed"] == 3
    assert receipt["source_run_id"] == RUN_ID
    assert receipt["junit_file"] == "root.xml"
    # The wiring also prints exactly one corroboration marker to stdout
    # with the same values as the receipt (the collector requires the
    # marker in the provider log before accepting any surplus).
    marker_lines = [line for line in proc.stdout.splitlines() if line.startswith("AGENT_OS_JUNIT_SUBTEST_RECEIPT")]
    assert len(marker_lines) == 1
