_SUBTEST_SOURCE = (
    "import unittest\n"
    "class T(unittest.TestCase):\n"
    "    def test_sub(self):\n"
    "        for i in range(3):\n"
    "            with self.subTest(i=i):\n"
    "                self.assertTrue(True)\n"
    "    def test_plain(self):\n"
    "        self.assertTrue(True)\n"
)


def _genuine_pass_fixture(tmp_path: Path) -> tuple[bytes, str]:
    """Run real pytest (verbose, as the root pytest.ini dictates) and
    return (junit bytes, captured terminal output)."""
    source = tmp_path / "test_sub.py"
    source.write_text(_SUBTEST_SOURCE, encoding="utf-8")
    report = tmp_path / "junit.xml"
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", str(source), "-v", "-p", "no:cacheprovider", f"--junitxml={report}"],
        cwd=tmp_path, capture_output=True, text=True, check=False,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    xml = report.read_bytes()
    from xml.etree import ElementTree as ET

    suite = ET.fromstring(xml).find("testsuite")
    assert len(suite.findall("testcase")) == 2
    if int(suite.attrib["tests"]) == 2:
        pytest.skip("this pytest does not count subtests in the tests attribute")
    assert int(suite.attrib["tests"]) == 5
    return xml, proc.stdout


def test_genuine_passing_subtests_accept_with_verified_receipt(tmp_path: Path) -> None:
    xml, output = _genuine_pass_fixture(tmp_path)
    with pytest.raises(ValueError, match="testcase-count-mismatch"):
        validate_junit(xml)
    entry = extract_entry(
        junit_bytes=xml, pytest_output=output, junit_file="junit.xml",
        source_run_id=RUN_ID, source_run_attempt=1, source_head=SOURCE_HEAD,
    )
    assert entry is not None
    assert entry["subtests_passed"] == 3
    assert entry["passed"] == 2
    assert entry["junit_tests"] == 5
    assert entry["junit_testcase_elements"] == 2
    ids, counts = verify_subtest_receipt(
        xml, entry, source_run_id=RUN_ID, source_run_attempt=1, source_head=SOURCE_HEAD,
        log_counts=_marker_counts(entry),
    )
    assert counts == {
        "tests": 5, "failures": 0, "errors": 0, "skipped": 0,
        "subtests_passed": 3, "testcase_elements": 2,
    }
    assert len(ids) == 2


def test_genuine_fixture_collector_path_accepts_and_rejects_without_receipt(tmp_path: Path) -> None:
    xml, output = _genuine_pass_fixture(tmp_path)
    entry = extract_entry(
        junit_bytes=xml, pytest_output=output, junit_file="junit.xml",
        source_run_id=RUN_ID, source_run_attempt=1, source_head=SOURCE_HEAD,
    )
    assert entry is not None

    def _zip(files: dict[str, bytes]) -> bytes:
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w") as zf:
            for name, data in files.items():
                zf.writestr(name, data)
        return buf.getvalue()

    bound = classify_junit_artifact(
        _zip({"junit.xml": xml, "junit-subtest-receipt-junit.json": json.dumps(entry).encode()}),
        source_run_id=RUN_ID, source_attempt=1, source_head=SOURCE_HEAD,
        log_markers={"junit": _marker_counts(entry)},
    )
    assert bound["classification"] == "EVIDENCE_VALID"
    assert bound["node_count"] == 2
    assert bound["counts"]["tests"] == 5
    assert bound["counts"]["testcase_elements"] == 2
    assert bound["counts"]["subtests_passed"] == 3
    # Same bytes, no receipt: no certified surplus acceptance.
    assert classify_junit_artifact(_zip({"junit.xml": xml}))["classification"] == "REJECT_SCHEMA"
    # Same bytes and receipt, but no provider binding: still rejected.
    assert classify_junit_artifact(
        _zip({"junit.xml": xml, "junit-subtest-receipt-junit.json": json.dumps(entry).encode()})
    )["classification"] == "REJECT_SCHEMA"
    # Same bytes, receipt, and binding -- but no provider-log marker:
    # a self-consistent receipt alone never certifies a surplus.
    assert classify_junit_artifact(
        _zip({"junit.xml": xml, "junit-subtest-receipt-junit.json": json.dumps(entry).encode()}),
        source_run_id=RUN_ID, source_attempt=1, source_head=SOURCE_HEAD,
    )["classification"] == "REJECT_SCHEMA"
    # Same, with a marker for a different suite: still uncorroborated.
    assert classify_junit_artifact(
        _zip({"junit.xml": xml, "junit-subtest-receipt-junit.json": json.dumps(entry).encode()}),
        source_run_id=RUN_ID, source_attempt=1, source_head=SOURCE_HEAD,
        log_markers={"other": _marker_counts(entry)},
    )["classification"] == "REJECT_SCHEMA"


