def test_verifier_requires_log_corroboration() -> None:
    # The trust-contract repair (2026-11-12): a source-bound receipt
    # that is internally consistent is NOT enough on its own. Without
    # a provider-log marker, or with a marker that disagrees, the
    # surplus stays rejected -- the earlier "self-consistent forged
    # receipt passes by design" disposition is superseded.
    xml = _xml(tests=5, cases=_passing_cases(2))
    entry = _entry_for(xml, passed=2, subtests_passed=3)
    with pytest.raises(ValueError, match="subtest-receipt-uncorroborated"):
        _verify(xml, entry, log_counts=None)
    with pytest.raises(ValueError, match="subtest-receipt-uncorroborated"):
        verify_subtest_receipt(xml, entry, source_run_id=RUN_ID, source_run_attempt=1, source_head=SOURCE_HEAD)
    mismatched = _marker_counts(entry)
    mismatched["subtests_passed"] = 2
    with pytest.raises(ValueError, match="subtest-marker-mismatch"):
        _verify(xml, entry, log_counts=mismatched)
    mismatched = _marker_counts(entry)
    mismatched["passed"] = 1
    with pytest.raises(ValueError, match="subtest-marker-mismatch"):
        _verify(xml, entry, log_counts=mismatched)
    mismatched = _marker_counts(entry)
    mismatched["junit_sha256"] = "0" * 64
    with pytest.raises(ValueError, match="subtest-marker-mismatch"):
        _verify(xml, entry, log_counts=mismatched)
    # The matching marker accepts (the verifier's other equations are
    # covered by test_verifier_accepts_passing_only_shape).
    _, counts = _verify(xml, entry)
    assert counts["subtests_passed"] == 3


