def _xml(*, tests: int, failures: int = 0, errors: int = 0, skipped: int = 0, cases: str) -> bytes:
    return (
        f'<?xml version="1.0"?><testsuites><testsuite name="pytest" tests="{tests}" '
        f'failures="{failures}" errors="{errors}" skipped="{skipped}">{cases}</testsuite></testsuites>'
    ).encode()


def _passing_cases(n: int) -> str:
    return "".join(f'<testcase classname="m" name="t{i}"/>' for i in range(n))


def _entry_for(xml: bytes, *, passed: int, skipped: int = 0, xfailed: int = 0,
               failed: int = 0, errors: int = 0, subtests_passed: int,
               run_id: int = RUN_ID, attempt: int = 1, head: str = SOURCE_HEAD,
               junit_file: str = "root.xml") -> dict:
    from scripts.agent_os_ci_evidence_health import parse_junit_report

    _, counts, _ = parse_junit_report(xml)
    return {
        "schema": SUBTEST_RECEIPT_SCHEMA,
        "junit_file": junit_file,
        "junit_sha256": hashlib.sha256(xml).hexdigest(),
        "source_run_id": run_id,
        "source_run_attempt": attempt,
        "source_head_sha": head,
        "passed": passed,
        "skipped": skipped,
        "xfailed": xfailed,
        "failed": failed,
        "errors": errors,
        "subtests_passed": subtests_passed,
        "junit_tests": counts["tests"],
        "junit_testcase_elements": counts["testcase_elements"],
        "junit_failures": counts["failures"],
        "junit_errors": counts["errors"],
        "junit_skipped": counts["skipped"],
    }


def _verify(xml: bytes, entry: dict, **binding) -> tuple:
    return verify_subtest_receipt(
        xml, entry,
        source_run_id=binding.get("run_id", RUN_ID),
        source_run_attempt=binding.get("attempt", 1),
        source_head=binding.get("head", SOURCE_HEAD),
    )


def test_verifier_accepts_passing_only_shape() -> None:
    # Mirrors the genuine root.xml shape at small scale: 2 passed
    # elements, declared 5, surplus 3 passing subtests.
    xml = _xml(tests=5, cases=_passing_cases(2))
    entry = _entry_for(xml, passed=2, subtests_passed=3)
    _, counts = _verify(xml, entry)
    assert counts["subtests_passed"] == 3
    assert counts["testcase_elements"] == 2


def test_verifier_rejects_unexplained_inflation() -> None:
    # One testcase declaring 9999 tests, with NO receipt, is rejected by
    # the collector: the surplus has no verified explanation.
    xml = _xml(tests=9999, cases=_passing_cases(1))
    assert classify_junit_artifact(_zip({"root.xml": xml}))["classification"] == "REJECT_SCHEMA"
    with pytest.raises(ValueError, match="testcase-count-mismatch"):
        validate_junit(xml)
    # A receipt stolen from a different report cannot explain it: the
    # digest and the recorded totals disagree with these bytes.
    other = _xml(tests=5, cases=_passing_cases(2))
    stolen = _entry_for(other, passed=2, subtests_passed=3)
    with pytest.raises(ValueError):
        _verify(xml, stolen)
    # A receipt for this report whose recorded totals were written for
    # a different declared total also fails the count cross-check.
    stale = _entry_for(xml, passed=1, subtests_passed=9998)
    stale["junit_tests"] = 5
    with pytest.raises(ValueError):
        _verify(xml, stale)
    # And a receipt whose claimed surplus does not match the actual
    # surplus fails the surplus equation.
    tampered = _entry_for(xml, passed=1, subtests_passed=9998)
    tampered["subtests_passed"] = 9997
    with pytest.raises(ValueError):
        _verify(xml, tampered)


def test_small_genuine_shape_accepts_only_with_receipt() -> None:
    # One testcase declaring three tests is exactly what one top-level
    # test with two passing subtests produces. Without a receipt it
    # stays rejected (the existing health control, preserved); with a
    # source-bound receipt that explains the surplus it is accepted.
    # The receipt -- not the surplus -- is what distinguishes the two.
    xml = _xml(tests=3, cases=_passing_cases(1))
    with pytest.raises(ValueError, match="testcase-count-mismatch"):
        validate_junit(xml)
    assert classify_junit_artifact(_zip({"root.xml": xml}))["classification"] == "REJECT_SCHEMA"
    _, counts = _verify(xml, _entry_for(xml, passed=1, subtests_passed=2))
    assert counts["subtests_passed"] == 2
    assert counts["testcase_elements"] == 1
    # A receipt claiming the wrong surplus for the same report fails.
    with pytest.raises(ValueError):
        _verify(xml, _entry_for(xml, passed=1, subtests_passed=1))


def test_verifier_rejects_setup_only_shape() -> None:
    # tests=0 with testcase elements is the --setup-only shape: elements
    # that look passing but never executed. It is rejected even with a
    # receipt, because a suite may not have more elements than tests.
    xml0 = _xml(tests=0, cases=_passing_cases(1))
    with pytest.raises(ValueError, match="testcase-count-mismatch"):
        validate_junit(xml0)
    with pytest.raises(ValueError):
        _verify(xml0, _entry_for(xml0, passed=0, subtests_passed=0))
    xml = _xml(tests=5, cases=_passing_cases(2))
    good = _entry_for(xml, passed=2, subtests_passed=3)
    with pytest.raises(ValueError):
        _verify(xml, _entry_for(xml, passed=2, subtests_passed=3, run_id=1))
    with pytest.raises(ValueError):
        _verify(xml, _entry_for(xml, passed=2, subtests_passed=3, attempt=2))
    with pytest.raises(ValueError):
        _verify(xml, _entry_for(xml, passed=2, subtests_passed=3, head="c" * 40))
    unbound = dict(good)
    unbound["source_run_id"] = None
    unbound["source_run_attempt"] = None
    unbound["source_head_sha"] = None
    with pytest.raises(ValueError):
        _verify(xml, unbound)
    # No binding supplied at all (legacy caller): never accepted.
    with pytest.raises(ValueError):
        verify_subtest_receipt(xml, good, source_run_id=None, source_run_attempt=None, source_head=None)


def test_verifier_rejects_digest_and_count_tampering() -> None:
    xml = _xml(tests=5, cases=_passing_cases(2))
    entry = _entry_for(xml, passed=2, subtests_passed=3)
    tampered_sha = dict(entry)
    tampered_sha["junit_sha256"] = "0" * 64
    with pytest.raises(ValueError):
        _verify(xml, tampered_sha)
    other_xml = _xml(tests=5, cases=_passing_cases(2).replace("t0", "u0"))
    with pytest.raises(ValueError):
        _verify(other_xml, entry)
    extra = dict(entry)
    extra["surprise"] = 1
    with pytest.raises(ValueError):
        _verify(xml, extra)


def test_verifier_rejects_skipped_and_xfail_subtest_shapes() -> None:
    # Genuine pytest 9.2.0 skipped-subtest shape: 2 passed top-level
    # tests, 1 skipped subtest; the parent element carries <skipped>,
    # so passed elements (1) != terminal passed (2).
    cases = '<testcase classname="m" name="plain"/><testcase classname="m" name="sub"><skipped/></testcase>'
    xml = _xml(tests=5, skipped=1, cases=cases)
    entry = _entry_for(xml, passed=2, skipped=1, subtests_passed=2)
    with pytest.raises(ValueError):
        _verify(xml, entry)
    # Xfail subtest shape: 1 passed top-level test, 1 xfailed subtest.
    cases = '<testcase classname="m" name="sub"><skipped/></testcase>'
    xml = _xml(tests=4, skipped=1, cases=cases)
    entry = _entry_for(xml, passed=1, xfailed=1, subtests_passed=2)
    with pytest.raises(ValueError):
        _verify(xml, entry)


def test_verifier_rejects_failed_and_error_shapes() -> None:
    cases = (
        '<testcase classname="m" name="plain"/>'
        '<testcase classname="m" name="sub"><failure message="x"/></testcase>'
    )
    xml = _xml(tests=5, failures=1, cases=cases)
    entry = _entry_for(xml, passed=2, failed=1, subtests_passed=2)
    with pytest.raises(ValueError):
        _verify(xml, entry)
    cases = '<testcase classname="m" name="t"><error message="boom"/></testcase>'
    xml = _xml(tests=2, errors=1, cases=cases + '<testcase classname="m" name="u"/>')
    entry = _entry_for(xml, passed=1, errors=1, subtests_passed=1)
    with pytest.raises(ValueError):
        _verify(xml, entry)


