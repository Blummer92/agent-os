def test_summary_nested_run_before_real_summary_does_not_win():
    # A nested pytest run printed by a test appears BEFORE the suite's
    # own final summary; the last matching line is still the suite's.
    text = (
        "platform linux -- Python 3.11.18, pytest-9.2.0\n"
        "===================== 59 passed in 19.19s =====================\n"
        "platform linux -- Python 3.11.18, pytest-9.2.0\n"
        "===================== 2 passed, 3 subtests passed in 0.03s =====================\n"
    )
    counts = parse_pytest_summary(text)
    assert counts is not None
    assert counts["passed"] == 2
    assert counts["subtests_passed"] == 3


def test_summary_forged_line_after_real_summary_wins_the_parse():
    # A summary line appended AFTER the real one (e.g. an atexit
    # handler) is what the extractor parses -- last match wins. The
    # safety net is the verifier, not the parser: a receipt built from
    # forged counts must still satisfy the XML equations, and one whose
    # surplus disagrees with the XML is rejected there (see
    # test_verifier_rejects_forged_summary_counts). The parser itself
    # never claims the line is genuine.
    text = (
        "===================== 2 passed, 3 subtests passed in 0.03s =====================\n"
        "===================== 2 passed, 99 subtests passed in 0.04s =====================\n"
    )
    counts = parse_pytest_summary(text)
    assert counts is not None
    assert counts["subtests_passed"] == 99


def test_junit_key_port_matches_bash_function():
    # Port of scripts/validate-all.sh junit_key(): "/" -> "__", then
    # every other byte outside [A-Za-z0-9._-] -> "_". Bash tr works on
    # bytes, so a multi-byte UTF-8 character becomes one "_" per byte
    # (QA note N1): "ü" is two bytes, "é" is two bytes.
    assert junit_key_for_suite("root") == "root"
    assert junit_key_for_suite("08_Tooling/workflow-scheduler") == "08_Tooling__workflow-scheduler"
    assert junit_key_for_suite("08_Tooling/agent-os-execution-service") == "08_Tooling__agent-os-execution-service"
    assert junit_key_for_suite("a b/c.d") == "a_b__c.d"
    assert junit_key_for_suite("ünicode/x") == "__nicode__x"
    assert junit_key_for_suite("café/test") == "caf____test"


def test_junit_key_port_agrees_with_bash_on_battery(tmp_path: Path) -> None:
    """Direct parity check: run the committed bash junit_key on a
    battery of names (including non-ASCII) and require the Python
    port to agree exactly."""
    import re
    import subprocess

    repo_root = Path(__file__).resolve().parents[1]
    script = (repo_root / "scripts/validate-all.sh").read_text(encoding="utf-8")
    match = re.search(r"^junit_key\(\) \{(.*?)^\}", script, re.MULTILINE | re.DOTALL)
    assert match is not None
    harness = f"junit_key() {{\n{match.group(1)}}}\n"
    names = ["root", "08_Tooling/workflow-scheduler", "a b/c.d", "ünicode/x", "café/test", "a$b", "a\tb", ""]
    # Pass names via argv (quoted safely) rather than embedding them.
    script_text = harness + 'for name in "$@"; do junit_key "$name"; echo; done\n'
    proc = subprocess.run(["bash", "-c", script_text, "junit_key_battery", *names],
                          capture_output=True, text=True, cwd=repo_root)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    bash_keys = proc.stdout.splitlines()
    assert len(bash_keys) == len(names), (bash_keys, names)
    for name, bash_key in zip(names, bash_keys):
        assert junit_key_for_suite(name) == bash_key, (name, bash_key, junit_key_for_suite(name))


