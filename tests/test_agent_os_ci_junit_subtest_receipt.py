def test_receipt_loader_rejects_malformed_and_duplicate_receipts() -> None:
    xml = _xml(tests=5, cases=_passing_cases(2))
    entry = _entry_for(xml, passed=2, subtests_passed=3)
    good = {"junit-subtest-receipt-root.json": json.dumps(entry).encode()}
    assert load_subtest_receipts(good) == {"root.xml": entry}
    with pytest.raises(ValueError):
        load_subtest_receipts({"junit-subtest-receipt-root.json": b"{not json"})
    wrong_schema = dict(entry)
    wrong_schema["schema"] = "other/1"
    with pytest.raises(ValueError):
        load_subtest_receipts({"junit-subtest-receipt-root.json": json.dumps(wrong_schema).encode()})
    dup = {
        "junit-subtest-receipt-a.json": json.dumps(entry).encode(),
        "junit-subtest-receipt-b.json": json.dumps(entry).encode(),
    }
    with pytest.raises(ValueError):
        load_subtest_receipts(dup)


