def _sample_marker_entry() -> dict:
    return {
        "passed": 11843, "skipped": 31, "xfailed": 1, "failed": 0, "errors": 0,
        "subtests_passed": 119, "junit_tests": 11994,
        "junit_sha256": "c820ae199cf9acf84a7299e6e29a7bd81c6ffff9f9b2adc3147730e00600fe6b",
    }


def test_marker_format_and_parse_round_trip() -> None:
    entry = _sample_marker_entry()
    line = format_subtest_marker(entry, "root")
    assert line.startswith("AGENT_OS_JUNIT_SUBTEST_RECEIPT suite=root ")
    assert "passed=11843" in line and "subtests_passed=119" in line
    assert "junit_sha256=c820ae199cf9acf84a7299e6e29a7bd81c6ffff9f9b2adc3147730e00600fe6b" in line
    parsed = parse_subtest_marker_line(line)
    assert parsed is not None
    assert parsed["suite_key"] == "root"
    assert parsed["passed"] == 11843
    assert parsed["subtests_passed"] == 119
    assert parsed["junit_tests"] == 11994
    # A GitHub timestamp prefix is stripped; the marker must start the
    # line content after it.
    stamped = "2026-11-11T19:35:44.2098772Z " + line
    assert parse_subtest_marker_line(stamped) == parsed
    # Ordinary lines are not markers.
    assert parse_subtest_marker_line("2026-11-11T19:35:44.2098772Z = 11843 passed, 31 skipped, 1 xfailed, 1 warning, 119 subtests passed in 272.09s (0:04:32) =") is None
    assert parse_subtest_marker_line("") is None


def test_marker_parser_ignores_midline_tag_and_pytest_summaries() -> None:
    # A tag embedded in a JSON string (a nested run's output printed by
    # a test) is not a marker: the tag must start the line.
    nested = '2026-11-11T19:31:02.8157029Z {"stdout_tail": "AGENT_OS_JUNIT_SUBTEST_RECEIPT suite=root passed=1 skipped=0 xfailed=0 failed=0 errors=0 subtests_passed=2 junit_tests=3 junit_sha256=' + "a" * 64 + '"}'
    assert parse_subtest_marker_line(nested) is None
    text = (
        "platform linux -- Python 3.11.18, pytest-9.2.0\n"
        "===================== 59 passed in 19.19s =====================\n"
        + nested + "\n"
    )
    assert parse_subtest_markers_text(text) == {}


def test_marker_parser_rejects_malformed_and_duplicate_markers() -> None:
    good = format_subtest_marker(_sample_marker_entry(), "root")
    with pytest.raises(ValueError, match="subtest-marker-conflict"):
        parse_subtest_marker_line(good.replace("passed=11843", "passed=-1"))
    with pytest.raises(ValueError, match="subtest-marker-conflict"):
        parse_subtest_marker_line(good + " extra=1")
    with pytest.raises(ValueError, match="subtest-marker-conflict"):
        parse_subtest_marker_line(good.replace("junit_sha256=c820", "junit_sha256=zzzz"))
    with pytest.raises(ValueError, match="subtest-marker-conflict"):
        parse_subtest_marker_line(good.replace("suite=root", "suite=ro ot"))
    # Two valid markers for one suite are ambiguous evidence, even
    # when identical: never silently pick one.
    with pytest.raises(ValueError, match="subtest-marker-duplicate"):
        parse_subtest_markers_text(good + "\n" + good + "\n")
    # Two valid markers that disagree are likewise a duplicate, not a
    # conflict: both parsed, and the suite has more than one claim.
    with pytest.raises(ValueError, match="subtest-marker-duplicate"):
        parse_subtest_markers_text(good.replace("passed=11843", "passed=11844") + "\n" + good + "\n")
    # Two different suites are fine.
    other = format_subtest_marker(_sample_marker_entry(), "other")
    found = parse_subtest_markers_text(good + "\n" + other + "\n")
    assert set(found) == {"root", "other"}


def test_log_zip_extraction_with_genuine_producer_line() -> None:
    # The genuine producer excerpt: its raw summary line alone must
    # NOT corroborate anything (no marker present); with the marker
    # for root, extraction returns root's counts.
    raw = (
        "2026-11-11T19:30:44.8285754Z ======================= 1829 passed, 7 skipped in 55.40s =======================\n"
        "2026-11-11T19:35:44.2098772Z = 11843 passed, 31 skipped, 1 xfailed, 1 warning, 119 subtests passed in 272.09s (0:04:32) =\n"
    )
    assert parse_subtest_markers_text(raw) == {}
    marker = format_subtest_marker(_sample_marker_entry(), "root")
    log = _zip({"1_Run aggregate validation.txt": (raw + "2026-11-11T19:35:44.2098772Z " + marker + "\n").encode()})
    found = extract_subtest_markers(log)
    assert found["root"]["subtests_passed"] == 119
    assert found["root"]["passed"] == 11843
    assert found["root"]["junit_tests"] == 11994
    # Truncated log (marker missing): empty, never zero-implied.
    truncated = _zip({"1_Run aggregate validation.txt": raw.encode()})
    assert extract_subtest_markers(truncated) == {}


def test_log_zip_extraction_rejects_ambiguous_and_unsafe_archives() -> None:
    marker = format_subtest_marker(_sample_marker_entry(), "root")
    dup = _zip({
        "1_Step one.txt": (marker + "\n").encode(),
        "2_Step two.txt": (marker + "\n").encode(),
    })
    with pytest.raises(ValueError, match="subtest-marker-duplicate"):
        extract_subtest_markers(dup)
    bad = _zip({"1_Step one.txt": (marker.replace("passed=11843", "passed=xx") + "\n").encode()})
    with pytest.raises(ValueError, match="subtest-marker-conflict"):
        extract_subtest_markers(bad)
    # Non-ZIP bytes are the job-level plain-text log shape (HIGH-1
    # repair): parsed as text, and text with no marker is empty, never
    # an error. Empty input remains invalid.
    assert extract_subtest_markers(b"not a zip") == {}
    with pytest.raises(ValueError):
        extract_subtest_markers(b"")
    traversal = _zip({"../evil.txt": (marker + "\n").encode()})
    with pytest.raises(ValueError):
        extract_subtest_markers(traversal)


def test_plaintext_job_log_bytes_parse_directly() -> None:
    # HIGH-1 repair: the jobs/{job_id}/logs endpoint serves plain text;
    # those bytes must corroborate exactly like the ZIP shape.
    marker = format_subtest_marker(_sample_marker_entry(), "root")
    raw = ("2026-11-11T19:35:44.2098772Z " + marker + "\n").encode()
    found = extract_subtest_markers(raw)
    assert found["root"]["subtests_passed"] == 119
    assert found["root"]["passed"] == 11843
    assert extract_subtest_markers(b"2026-11-11T19:30:44.8285754Z ordinary output\n") == {}


def test_scoped_extraction_confines_and_flags_foreign_markers() -> None:
    # MED-1 repair: with job/step scope bound, only the bound job/step
    # member corroborates. A marker line in a foreign job's member, a
    # different step's member, or an unrelated member is conflicting
    # evidence and raises ValueError (never corroboration, never
    # silently ignored); out-of-scope non-marker content is ignored.
    # Unscoped callers keep the legacy whole-archive behavior.
    marker = format_subtest_marker(_sample_marker_entry(), "root")
    job = "Run aggregate validation"
    bound = _zip({f"{job}/15_Run aggregate validation.txt": (marker + "\n").encode()})
    scoped = extract_subtest_markers(bound, job_name=job, step_name="Run aggregate validation")
    assert scoped["root"]["subtests_passed"] == 119
    # Job-level layout (step files at the archive root) stays in scope.
    job_level = _zip({"1_Run aggregate validation.txt": (marker + "\n").encode()})
    assert extract_subtest_markers(job_level, job_name=job, step_name="Run aggregate validation")["root"]["passed"] == 11843
    for members in (
        {"Run frontend checks/1_Run frontend checks.txt": (marker + "\n").encode()},
        {f"{job}/3_Set up job.txt": (marker + "\n").encode()},
        {"totally/unrelated.txt": (marker + "\n").encode()},
    ):
        with pytest.raises(ValueError, match="subtest-marker-out-of-scope"):
            extract_subtest_markers(_zip(members), job_name=job, step_name="Run aggregate validation")
    unrelated = _zip({"totally/unrelated.txt": (marker + "\n").encode()})
    assert extract_subtest_markers(unrelated)["root"]["subtests_passed"] == 119


