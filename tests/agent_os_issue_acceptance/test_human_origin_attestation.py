"""Human-origin attestation boundary tests (#3463, S2 owner decision).

A merge-authorization record is an auditable representation only. It must
never, by itself, establish human-origin authority for a production merge.
Only a fresh runtime human approval card tap for exactly the dispatch
receipt's human_origin_attestation.binding parameters can do that, and
repository evaluation never observes the card -- so every repository
receipt reports attestation as required-but-not-observed and
merge_authorized False, even for a perfect-looking owner comment.

No test here performs a merge; the fake GitHub surface is read-only.
"""
from __future__ import annotations

import importlib.util
import inspect
import sys
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from scripts.agent_os_issue_acceptance import merge_admission_actions as actions  # noqa: E402
from scripts.agent_os_issue_acceptance.merge_applicability import (  # noqa: E402
    evaluate_merge_dispatch_applicability,
)
from scripts.agent_os_issue_acceptance.merge_authorization_source import (  # noqa: E402
    serialize_merge_authorization_comment,
)

_HERE = Path(__file__).parent
_spec = importlib.util.spec_from_file_location(
    "_tdispatch", _HERE / "test_merge_applicability.py"
)
_tdispatch = importlib.util.module_from_spec(_spec)
sys.modules["_tdispatch"] = _tdispatch
_spec.loader.exec_module(_tdispatch)


def _attestation(receipt):
    attestation = receipt["human_origin_attestation"]
    assert attestation["status"] == "required-not-observed"
    assert attestation["mechanism"] == "runtime-human-approval-card"
    assert attestation["observed_by_repository"] is False
    return attestation


def test_content_passing_owner_comment_does_not_attest_human_origin():
    """The core S2 proof: a perfect owner comment still cannot attest."""
    bundle = None
    record = _tdispatch._authorized_record(bundle)
    receipt = _tdispatch._run(bundle=bundle, record=record)
    assert receipt["dispatch_checks_passed"] is True
    assert receipt["canonical_applicability_result"]["status"] == "applicable"
    assert receipt["canonical_applicability_result"]["merge_authorized"] is True
    # ...but execution authorization is a different verdict, and the
    # repository cannot supply it.
    assert receipt["status"] == "awaiting-human-attestation"
    assert receipt["merge_authorized"] is False
    assert receipt["reason_codes"] == ["human-origin-attestation-required"]
    attestation = _attestation(receipt)
    assert attestation["binding"] == {
        "repository": _tdispatch.REPO,
        "pr_number": _tdispatch.PR_NUMBER,
        "head_sha": _tdispatch.HEAD,
        "base_branch": "main",
        "base_sha": _tdispatch.BASE,
        "merge_method": "squash",
        "authorization_id": record.authorization_id,
        "authorization_revision": record.authorization_revision,
        "changed_scope_fingerprint": record.binding.changed_scope_fingerprint,
    }


def test_dispatch_api_accepts_no_attestation_input():
    """An agent cannot inject attestation: dispatch takes no such input."""
    parameters = inspect.signature(evaluate_merge_dispatch_applicability).parameters
    assert not any("attest" in name for name in parameters)
    assert set(parameters) == {"transport", "repository", "github_client", "evaluated_at"}


def test_app_performed_owner_comment_blocks_dispatch():
    bundle = None
    record = _tdispatch._authorized_record(bundle)
    comments = _tdispatch._comments_for(bundle, record)
    for comment in comments:
        comment.performed_via_github_app = SimpleNamespace(
            slug="chatgpt-codex-connector"
        )
    receipt = _tdispatch._run(bundle=bundle, record=record, comments=comments)
    assert receipt["dispatch_checks_passed"] is False
    assert receipt["merge_authorized"] is False
    assert "merge-dispatch-blocked-by-admission" in receipt["reason_codes"]
    _attestation(receipt)


def test_footer_bearing_owner_comment_blocks_dispatch():
    bundle = None
    record = _tdispatch._authorized_record(bundle)
    pending = _tdispatch._pending_for(record)
    comments = [
        _tdispatch._Comment(
            10, serialize_merge_authorization_comment(pending)
        ),
        _tdispatch._Comment(
            11,
            serialize_merge_authorization_comment(record)
            + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
        ),
    ]
    receipt = _tdispatch._run(bundle=bundle, record=record, comments=comments)
    assert receipt["dispatch_checks_passed"] is False
    assert receipt["merge_authorized"] is False
    assert "merge-dispatch-blocked-by-admission" in receipt["reason_codes"]
    _attestation(receipt)


def test_stale_head_blocks_and_expected_head_stays_pinned():
    receipt = _tdispatch._run(
        pr=_tdispatch._PR(head=_tdispatch._Ref("refs/heads/feat", "f" * 40))
    )
    assert receipt["dispatch_checks_passed"] is False
    assert receipt["merge_authorized"] is False
    _attestation(receipt)
    # Admission blocks before any record is acquired, so no binding is
    # published -- but the receipt's expected head stays pinned to the
    # authorized head, never to the drifted live head: a card tapped for
    # the drifted head would not match this receipt.
    assert receipt["expected_head_sha"] == _tdispatch.HEAD
    assert receipt["human_origin_attestation"]["binding"] is None


def test_replayed_consumed_record_blocks_dispatch():
    from dataclasses import replace

    bundle = None
    record = _tdispatch._authorized_record(bundle)
    # A consumed successor chained onto the SAME authorization id: the
    # source must report the chain stale, not current, so dispatch blocks.
    consumed = replace(
        record, authorization_id="", authorization_revision="",
        revision_number=record.revision_number + 1,
        previous_revision=record.authorization_revision,
        state=_tdispatch._tauth.MergeAuthorizationState.CONSUMED,
        decision_id="merge-observed", decision_at="2026-07-26T14:45:00Z",
        consumed_observation_id="merge-execution-observation:" + "e" * 64,
        reason_codes=("authorization.consumed",),
    )
    comments = _tdispatch._comments_for(bundle, record)
    comments.append(
        _tdispatch._Comment(16, serialize_merge_authorization_comment(consumed))
    )
    receipt = _tdispatch._run(bundle=bundle, record=consumed, comments=comments)
    assert receipt["dispatch_checks_passed"] is False
    assert receipt["merge_authorized"] is False
    assert "merge-dispatch-blocked-by-admission" in receipt["reason_codes"]
    _attestation(receipt)


def test_conflicting_merge_method_blocks_dispatch():
    receipt = _tdispatch._run(
        transport=_tdispatch._transport(merge_admission_method_or_none="merge")
    )
    assert receipt["dispatch_checks_passed"] is False
    assert receipt["merge_authorized"] is False
    _attestation(receipt)


def test_admission_candidate_also_carries_the_card_requirement():
    bundle = None
    record = _tdispatch._authorized_record(bundle)
    comments = _tdispatch._comments_for(bundle, record)
    client = _tdispatch._Client(_tdispatch._Repo(_tdispatch._PR(), comments))
    candidate = actions.evaluate_merge_admission_transport(
        _tdispatch._transport(), repository=_tdispatch.REPO,
        github_client=client, evaluated_at=_tdispatch.NOW,
    )
    assert candidate["merge_authorized"] is False
    contract = candidate["host_dispatch_contract"]
    assert "receipt.status == 'awaiting-human-attestation'" in (
        contract["merge_dispatch_allowed_only_when_all_true"]
    )
    assert any(
        "fresh per-call runtime human approval card was tapped" in item
        for item in contract["merge_dispatch_allowed_only_when_all_true"]
    )
    assert any(
        "GitHub comment" in item for item in contract["forbidden"]
    )
