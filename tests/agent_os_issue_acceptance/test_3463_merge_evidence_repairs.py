"""Regression tests for three merge-evidence defects (#3463, non-closing).

1. PullRequestMergeEvidence rejected real PR bodies above 4,096 bytes.
2. ``pull-request.multiple-implemented-issues`` was emitted but missing from
   the reason-code vocabulary, so evaluation raised instead of refusing.
3. Approval-comment footer normalization ignored the actual
   ``https://claude.ai/code`` footer.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from scripts.agent_os_issue_acceptance import merge_authorization as ma  # noqa: E402
from scripts.agent_os_issue_acceptance.approval_source import (  # noqa: E402
    APPROVAL_MARKER,
    ApprovalCommentSnapshot,
    ApprovalSourceSnapshot,
    reacquire_approval_source,
    serialize_approval_comment,
)

_spec = importlib.util.spec_from_file_location(
    "_tauth_3463", Path(__file__).parent / "test_merge_authorization.py")
_t = importlib.util.module_from_spec(_spec)
sys.modules["_tauth_3463"] = _t
_spec.loader.exec_module(_t)


# ---- 1. PR title/body bound -------------------------------------------------
def test_real_world_pr_body_above_generic_bound_is_evaluable():
    body = "x" * 9503  # PR #3729's real body size
    pr = _t._pr(pr_body=body, pr_metadata_sha256="")
    assert pr.pr_body == body
    record, bundle = _t._authorized()
    result = _t._evaluate(record, bundle, pr=_t._pr(bundle, pr_body=body))
    assert "evidence.malformed" not in result.reason_codes


def test_pr_text_remains_bounded_and_nul_free():
    with pytest.raises(ValueError, match="bounded byte length"):
        ma._pr_text("x" * (4 * 65536 + 1), "pr_body")
    with pytest.raises(ValueError, match="NUL-free"):
        ma._pr_text("a\x00b", "pr_body")
    assert ma._pr_text("x" * (4 * 65536), "pr_body")


def test_generic_text_bound_is_unchanged():
    with pytest.raises(ValueError, match="bounded byte length"):
        ma._text("x" * 4097, "context")


# ---- 2. multiple-implemented-issues reason code ------------------------------
def test_reason_code_is_in_the_vocabulary_and_blocking():
    assert "pull-request.multiple-implemented-issues" in ma.MERGE_AUTHORIZATION_REASON_CODES
    assert "pull-request.multiple-implemented-issues" in ma._BLOCKED


def test_dual_implemented_issue_claims_yield_typed_refusal_not_exception():
    record, bundle = _t._authorized()
    result = _t._evaluate(
        record, bundle, pr=_t._pr(bundle, pr_body="Closes #11\nFixes #12"))
    assert not result.merge_authorized
    assert "pull-request.multiple-implemented-issues" in result.reason_codes
    assert result.status != "applicable"


# ---- 3. approval footer ------------------------------------------------------
_FOOTERS = [
    "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
    "\n\n---\n_Generated by [Claude Code](https://claude.ai)_",
]


def _source(body):
    bundle = _t._bundle()
    snap = ApprovalSourceSnapshot(
        repository="blummer92/agent-os", pr_number=630, owner_login="Blummer92",
        owner_type="User", comments_complete=True,
        comments=(ApprovalCommentSnapshot(1, "Blummer92", "2026-07-26T14:50:00Z", body),))

    class T:
        def read_approval_source(self, repository, pr_number):
            return snap

    return reacquire_approval_source(
        transport=T(), repository="blummer92/agent-os", pr_number=630), bundle


@pytest.mark.parametrize("footer", _FOOTERS)
def test_known_footers_are_stripped_from_approval_comments(footer):
    bundle = _t._bundle()
    from scripts.agent_os_issue_acceptance import serialize_approval_record
    body = serialize_approval_comment(APPROVAL_MARKER, serialize_approval_record(bundle[0]))
    result, _ = _source(body + footer)
    assert result.reason_codes != ("source.trusted-record-malformed",)
    assert result.status.value != "needs-decision"


def test_unknown_or_doubled_footers_still_fail_closed():
    bundle = _t._bundle()
    from scripts.agent_os_issue_acceptance import serialize_approval_record
    body = serialize_approval_comment(APPROVAL_MARKER, serialize_approval_record(bundle[0]))
    for text in (body + "\n\n---\n_Generated by [Claude Code](https://evil.example)_",
                 body + _FOOTERS[0] + _FOOTERS[0]):
        result, _ = _source(text)
        assert result.reason_codes == ("source.trusted-record-malformed",)
