"""#3690 AC5: ``validate-draft`` ingress tolerates one known agent attribution footer.

Reproduction (#3690 "Reproduction / current motivation"): an agent session that
is required to end every GitHub comment with the Claude Code attribution footer
can never post a byte-exact ``/agent-os validate-draft <pr> <sha>`` command, so
the strict ``fullmatch`` ingress answered ``ignored / malformed-trigger`` and the
owner had to paste the command by hand. ``refresh-pr`` already tolerates exactly
one known footer (#3730); ``validate-draft`` did not.

The repair is deliberately narrow and this file pins every boundary it must not
move: exactly one *known* trailing footer, ``validate-draft`` only, grammar and
actor/repository/event gates unchanged, no footer tolerance for any other
operation (``merge_authorization_source`` rejects footers on purpose, because a
footer is in-band evidence of agent authorship).
"""
from __future__ import annotations

import pytest

from workflow_scheduler.governance.github_issue_comment_ingress import (
    admit_issue_comment_event,
)

REPOSITORY = "Blummer92/agent-os"
ACTOR = "Blummer92"
SERVICE_ACTOR = "chatgpt-codex-connector[bot]"
HEAD_SHA = "a" * 40
TRIGGER = f"/agent-os validate-draft 3687 {HEAD_SHA}"

# The two footers recognised by the established #3730 convention. Spelled out
# here (not imported) so a drift in the production tuple fails these tests.
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
LEGACY_FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai)_"


def event(body: object, *, actor: str = ACTOR, issue: dict | None = None) -> dict:
    return {
        "action": "created",
        "repository": {"full_name": REPOSITORY},
        "issue": issue if issue is not None else {"number": 3502},
        "comment": {"id": 7001, "body": body, "user": {"login": actor}},
        "sender": {"login": actor},
    }


def admit(payload: object, *, service: bool = False, run_attempt: int = 1):
    return admit_issue_comment_event(
        payload,
        expected_repository=REPOSITORY,
        allowed_actor=ACTOR,
        run_attempt=run_attempt,
        draft_validation_service_actor=SERVICE_ACTOR if service else None,
    )


MALFORMED = ("ignored", "malformed-trigger")


# --- positive: the reproduced defect ------------------------------------------


@pytest.mark.parametrize("footer", [FOOTER, LEGACY_FOOTER], ids=["current", "legacy"])
def test_owner_validate_draft_with_one_known_footer_is_accepted(footer: str) -> None:
    result = admit(event(TRIGGER + footer))
    assert (result.status, result.reason) == ("accepted", "accepted-draft-validation-envelope")
    assert result.draft_validation_pr_number_or_none == 3687
    assert result.draft_validation_head_sha_or_none == HEAD_SHA
    # Non-authorizing transport evidence, exactly as for the byte-exact command.
    assert result.execution_authorized is False
    assert result.scheduler_invoked is False
    assert result.side_effects_performed is False


def test_footer_bearing_command_deduplicates_against_the_exact_command() -> None:
    # The logical trigger id is derived from repository/issue/PR/head only, so a
    # footer-bearing retry can never become a second, distinct validation.
    exact = admit(event(TRIGGER))
    footered = admit(event(TRIGGER + FOOTER))
    assert exact.logical_trigger_id_or_none is not None
    assert footered.logical_trigger_id_or_none == exact.logical_trigger_id_or_none


def test_service_actor_footer_bearing_validate_draft_is_accepted() -> None:
    result = admit(event(TRIGGER + FOOTER, actor=SERVICE_ACTOR), service=True)
    assert (result.status, result.reason) == ("accepted", "accepted-draft-validation-envelope")
    assert result.actor == SERVICE_ACTOR


# --- negative: tolerance is exactly one KNOWN trailing footer -----------------


@pytest.mark.parametrize(
    "body",
    [
        TRIGGER + FOOTER + FOOTER,  # two footers
        TRIGGER + FOOTER + LEGACY_FOOTER,  # one of each
        TRIGGER + FOOTER + " --force",  # text after the footer
        TRIGGER + FOOTER + "\n",  # trailing newline after the footer
        TRIGGER + " extra" + FOOTER,  # extra token before the footer
        TRIGGER + "; rm -rf /" + FOOTER,  # shell syntax before the footer
        TRIGGER + "\n" + TRIGGER + FOOTER,  # a second command line
        TRIGGER + "\n\n---\n_Generated by [Claude Code](https://claude.ai/evil)_",  # unknown URL
        TRIGGER + "\n\n---\n_Generated by [Other Agent](https://claude.ai/code)_",  # unknown agent
        TRIGGER + "\n---\n_Generated by [Claude Code](https://claude.ai/code)_",  # wrong spacing
        TRIGGER + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)",  # truncated
        TRIGGER + FOOTER.strip(),  # no separating blank line
        TRIGGER + "\n" + FOOTER,  # extra newline before the footer
        TRIGGER + " " + FOOTER,  # trailing space before the footer
        TRIGGER + "\t" + FOOTER,  # trailing tab before the footer
        TRIGGER + "\r" + FOOTER,  # CR before the footer
        TRIGGER + FOOTER.replace("\n", "\r\n"),  # CRLF footer
        FOOTER,  # footer alone
        "\n\n" + TRIGGER + FOOTER,  # leading whitespace before the command
    ],
    ids=lambda value: repr(value)[-48:],
)
def test_anything_but_one_known_trailing_footer_stays_malformed(body: str) -> None:
    result = admit(event(body))
    assert (result.status, result.reason) == MALFORMED
    assert result.draft_validation_pr_number_or_none is None
    assert result.draft_validation_head_sha_or_none is None


@pytest.mark.parametrize(
    "command",
    [
        f"/agent-os validate-draft 0 {HEAD_SHA}",  # PR number may not be zero
        f"/agent-os validate-draft 03687 {HEAD_SHA}",  # no leading zeros
        "/agent-os validate-draft 3687 " + "a" * 39,  # short SHA
        "/agent-os validate-draft 3687 " + "A" * 40,  # upper-case SHA
        "/agent-os validate-draft " + HEAD_SHA,  # missing PR number
    ],
)
def test_footer_never_repairs_a_malformed_selector(command: str) -> None:
    result = admit(event(command + FOOTER))
    assert (result.status, result.reason) == MALFORMED


# --- negative: no tolerance for any other operation ---------------------------

# One VALID byte-exact command for EVERY other ingress operation (grammar read from
# github_issue_comment_ingress), with the issue number the operation is bound to
# where it is bound. The exact form must be accepted for the owner, so the
# footer-bearing form is rejected for the footer alone, never for a bad grammar.
OTHER_OPERATIONS = [
    ("discover", "/agent-os discover", 3502),
    ("inspect-runtime", "/agent-os inspect-runtime", 3502),
    ("resume", f"/agent-os resume executor-handoff:{'a' * 64}", 3502),
    ("ready-admit", f"/agent-os ready-admit 3687 {HEAD_SHA} {'b' * 64}", 3502),
    ("merge-admit", f"/agent-os merge-admit 3687 {HEAD_SHA} {'b' * 64} squash", 3502),
    (
        "recover-ready",
        f"/agent-os recover-ready 3687 {HEAD_SHA} {'b' * 40} {'c' * 40} 40000000001",
        3502,
    ),
    (
        "dev-validate",
        f"/agent-os dev-validate agent/3687-example {HEAD_SHA} remote-validation-suite",
        3502,
    ),
    ("notion-read", "/agent-os notion-read req-123", 3502),
    (
        "activate-first-publication",
        f"/agent-os activate-first-publication pre-publication-evidence:{'a' * 64}",
        3502,
    ),
    ("diagnose", "/agent-os diagnose ppux-canva-cdp-readonly req-123", 3502),
    (
        "project-ppux-prompts",
        f"/agent-os project-ppux-prompts agent/3687-example {HEAD_SHA} {'a' * 64}",
        3502,
    ),
    (
        "codespace-implementation",
        f"/agent-os codespace-implementation executor-handoff:{'a' * 64} {HEAD_SHA}",
        3333,
    ),
    (
        "apply-required-validation-gate",
        f"/agent-os apply-required-validation-gate {'a' * 64}",
        2234,
    ),
    ("codespace-start", "/agent-os codespace-start", 3345),
]


@pytest.mark.parametrize(
    ("command", "issue_number"),
    [(command, issue) for _, command, issue in OTHER_OPERATIONS],
    ids=[name for name, _, _ in OTHER_OPERATIONS],
)
def test_other_operations_still_reject_a_footer(command: str, issue_number: int) -> None:
    exact = admit(event(command, issue={"number": issue_number}))
    assert exact.status == "accepted", "table entry must be a valid byte-exact command"
    footered = admit(event(command + FOOTER, issue={"number": issue_number}))
    assert (footered.status, footered.reason) == MALFORMED


def test_the_table_covers_every_fixed_operation_grammar() -> None:
    # Guard against the table silently missing a newly added ingress operation:
    # every distinct "/agent-os <verb>" accepted by the parser appears above.
    verbs = {command.split()[1] for _, command, _ in OTHER_OPERATIONS} | {"validate-draft"}
    assert verbs == {
        "discover",
        "inspect-runtime",
        "resume",
        "ready-admit",
        "merge-admit",
        "recover-ready",
        "dev-validate",
        "notion-read",
        "activate-first-publication",
        "diagnose",
        "project-ppux-prompts",
        "codespace-implementation",
        "apply-required-validation-gate",
        "codespace-start",
        "validate-draft",
    }


# --- negative: actor / repository / event gates are unchanged -----------------


def test_unauthorized_actor_is_still_blocked_before_the_body_is_read() -> None:
    result = admit(event(TRIGGER + FOOTER, actor="mallory"))
    assert (result.status, result.reason) == ("blocked", "actor-not-allowed")


def test_service_actor_requires_explicit_opt_in_even_with_a_footer() -> None:
    result = admit(event(TRIGGER + FOOTER, actor=SERVICE_ACTOR), service=False)
    assert (result.status, result.reason) == ("blocked", "actor-not-allowed")


def test_service_actor_footer_on_another_operation_is_blocked() -> None:
    result = admit(event("/agent-os discover" + FOOTER, actor=SERVICE_ACTOR), service=True)
    assert (result.status, result.reason) == ("blocked", "actor-not-allowed")


def test_sender_must_match_the_comment_author() -> None:
    payload = event(TRIGGER + FOOTER)
    payload["sender"] = {"login": "mallory"}
    result = admit(payload)
    assert (result.status, result.reason) == ("blocked", "actor-evidence-mismatch")


def test_foreign_repository_rerun_and_non_created_events_still_block() -> None:
    foreign = event(TRIGGER + FOOTER)
    foreign["repository"] = {"full_name": "someone/else"}
    assert admit(foreign).reason == "repository-mismatch"
    assert admit(event(TRIGGER + FOOTER), run_attempt=2).reason == "workflow-rerun"
    edited = event(TRIGGER + FOOTER)
    edited["action"] = "edited"
    assert admit(edited).reason == "event-not-created"


def test_pull_request_conversation_comments_are_still_ignored() -> None:
    payload = event(TRIGGER + FOOTER, issue={"number": 3687, "pull_request": {"url": "x"}})
    result = admit(payload)
    assert (result.status, result.reason) == ("ignored", "pull-request-comment")


@pytest.mark.parametrize("body", [None, 7, ["a"], b"bytes"])
def test_non_string_bodies_remain_malformed(body: object) -> None:
    result = admit(event(body))
    assert (result.status, result.reason) == MALFORMED


def test_oversized_footer_bearing_body_remains_malformed() -> None:
    # Padded bodies stay rejected. (A valid footer-bearing command is at most ~135
    # bytes, so the 256-byte raw-body bound cannot interact with the strip; this
    # pins only that padding cannot smuggle a command past the bound.)
    oversized = TRIGGER + " " + "x" * 200 + FOOTER
    assert len(oversized.encode("utf-8")) > 256
    result = admit(event(oversized))
    assert (result.status, result.reason) == MALFORMED
