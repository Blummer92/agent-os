"""Retry already-applied validation against production request shapes.

The real Docs/Slides request builders
(``docs_requests.build_docs_replace_requests`` /
``slides_requests.build_slides_replace_requests``) emit the API-native
string-valued ``replaceText``. Every request fixture below is generated by
those production builders — never hand-written — so these tests prove the
retry safety net understands the shape the build actually sends.

Red/green contract: the already-applied acceptance tests FAIL against the
pre-repair ``_already_applied()`` (which only understood a dict-shaped
``{"replaceText": {"text": ...}}`` fixture) and PASS after the repair.
Fail-closed tests pass before and after.
"""
from __future__ import annotations

import pytest

from instructional_materials_coach.content_spec import content_from_dict
from instructional_materials_coach.docs_requests import build_docs_replace_requests
from instructional_materials_coach.slides_requests import build_slides_replace_requests
from instructional_materials_coach.workspace_clients import (
    _already_applied,
    _validate_replace_results,
)

TITLE_TEXT = "Fractions Intro"


def _sample_content():
    return content_from_dict(
        {
            "title": TITLE_TEXT,
            "objectives": ["Add fractions"],
            "slides": [{"index": 1, "bullets": ["Candy Branding"]}],
            "worksheet_questions": ["What is 1/4 + 2/4?"],
        }
    )


def _replacement_strings(requests):
    return [r["replaceAllText"]["replaceText"] for r in requests]


def _zero_replies(requests, changed=0):
    return {"replies": [{"replaceAllText": {"occurrencesChanged": changed}} for _ in requests]}


def test_docs_already_applied_production_request_accepted():
    """Docs: occurrencesChanged=0 with the replacement text already present."""
    requests = build_docs_replace_requests(_sample_content())
    assert all(isinstance(t, str) for t in _replacement_strings(requests))
    present_text = "worksheet body :: " + " :: ".join(_replacement_strings(requests))
    # Must not raise: the retry proves the replacement is already applied.
    _validate_replace_results(
        requests, _zero_replies(requests), surface="Docs",
        content_fetcher=lambda: present_text,
    )


def test_slides_already_applied_production_request_accepted():
    """Slides: occurrencesChanged=0 with the replacement text already present."""
    requests = build_slides_replace_requests(_sample_content())
    assert all(isinstance(t, str) for t in _replacement_strings(requests))
    present_text = "slide deck :: " + " :: ".join(_replacement_strings(requests))
    _validate_replace_results(
        requests, _zero_replies(requests), surface="Slides",
        content_fetcher=lambda: present_text,
    )


def test_genuinely_missing_replacement_fails_closed():
    """occurrencesChanged=0 with the text genuinely absent must still fail."""
    requests = build_docs_replace_requests(_sample_content())
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, _zero_replies(requests), surface="Docs",
            content_fetcher=lambda: "unrelated document text without any token content",
        )


@pytest.mark.parametrize("surface", ["Docs", "Slides"])
def test_genuinely_missing_replacement_fails_closed_both_surfaces(surface):
    builders = {"Docs": build_docs_replace_requests, "Slides": build_slides_replace_requests}
    requests = builders[surface](_sample_content())
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, _zero_replies(requests), surface=surface,
            content_fetcher=lambda: "unrelated text",
        )


def test_empty_replace_text_fails_closed():
    """An empty replacement string is not observable evidence: fail closed."""
    requests = [
        {
            "replaceAllText": {
                "containsText": {"text": "{{empty}}", "matchCase": True},
                "replaceText": "",
            }
        }
    ]
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, _zero_replies(requests), surface="Docs",
            content_fetcher=lambda: "some document text",
        )


def test_dict_shaped_replace_text_is_malformed_and_fails_closed():
    """The legacy dict-shaped fixture is not a production shape: fail closed.

    The pre-repair validator accepted this shape; the repair treats it as
    malformed replacement evidence rather than proof of application.
    """
    requests = [
        {
            "replaceAllText": {
                "containsText": {"text": "{{title}}", "matchCase": True},
                "replaceText": {"text": TITLE_TEXT},
            }
        }
    ]
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, _zero_replies(requests), surface="Docs",
            content_fetcher=lambda: f"prefix {TITLE_TEXT} suffix",
        )


def test_missing_replace_text_key_fails_closed():
    requests = [
        {"replaceAllText": {"containsText": {"text": "{{title}}", "matchCase": True}}}
    ]
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, _zero_replies(requests), surface="Docs",
            content_fetcher=lambda: f"prefix {TITLE_TEXT} suffix",
        )


def test_non_dict_replace_request_is_skipped():
    """A request that is not a dict has no replaceAllText: the validator skips it.

    This is pre-existing envelope behavior, unchanged by the repair.
    """
    _validate_replace_results(
        ["not-a-request"],
        {"replies": [{"replaceAllText": {"occurrencesChanged": 0}}]},
        surface="Docs",
        content_fetcher=lambda: TITLE_TEXT,
    )


@pytest.mark.parametrize(
    "fetcher",
    [
        pytest.param(lambda: (_ for _ in ()).throw(RuntimeError("read failed")), id="raises"),
        pytest.param(lambda: None, id="returns-none"),
        pytest.param(lambda: "", id="returns-empty"),
        pytest.param(lambda: 123, id="returns-non-string"),
    ],
)
def test_unreadable_content_readback_fails_closed(fetcher):
    """A failed or unavailable content readback is never proof: fail closed."""
    requests = build_slides_replace_requests(_sample_content())
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, _zero_replies(requests), surface="Slides",
            content_fetcher=fetcher,
        )


def test_multiple_requests_mixed_outcomes():
    """Several requests: changed=1 passes, 0+present passes, 0+absent raises."""
    requests = build_docs_replace_requests(_sample_content())
    assert len(requests) >= 3
    texts = _replacement_strings(requests)
    present = " :: ".join(texts[:-1])  # last request's text is absent
    replies = {
        "replies": [
            {"replaceAllText": {"occurrencesChanged": 1}},
            *[{"replaceAllText": {"occurrencesChanged": 0}} for _ in requests[1:]],
        ]
    }
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(
            requests, replies, surface="Docs", content_fetcher=lambda: present
        )


def test_multiple_requests_all_proven_pass():
    """Several requests: every 0-changed request proven present → accepted."""
    requests = build_slides_replace_requests(_sample_content())
    present = "deck :: " + " :: ".join(_replacement_strings(requests))
    _validate_replace_results(
        requests, _zero_replies(requests), surface="Slides",
        content_fetcher=lambda: present,
    )


def test_normal_first_attempt_generation_unaffected():
    """Hot path (no fetcher): occurrencesChanged=1 is accepted, unchanged."""
    requests = build_docs_replace_requests(_sample_content())
    ok = {"replies": [{"replaceAllText": {"occurrencesChanged": 1}} for _ in requests]}
    _validate_replace_results(requests, ok, surface="Docs")


def test_zero_occurrences_without_fetcher_still_fails():
    """Hot path: occurrencesChanged=0 without a fetcher still fails as before."""
    requests = build_docs_replace_requests(_sample_content())
    with pytest.raises(RuntimeError, match="required placeholder was not replaced"):
        _validate_replace_results(requests, _zero_replies(requests), surface="Docs")


def test_non_replace_requests_are_skipped():
    """Requests without replaceAllText are not subject to the placeholder check."""
    requests = [{"updateTextStyle": {"objectId": "p1"}}]
    response = {"replies": [{"updateTextStyle": {}}]}
    _validate_replace_results(requests, response, surface="Docs",
                              content_fetcher=lambda: "anything")


# Direct _already_applied unit coverage. The helper takes the inner
# ``replaceAllText`` mapping, exactly as _validate_replace_results passes it.

def _replace(text):
    return {"containsText": {"text": "{{t}}"}, "replaceText": text}


def test_already_applied_accepts_exact_string_evidence():
    assert _already_applied(lambda: f"a {TITLE_TEXT} b", _replace(TITLE_TEXT)) is True


def test_already_applied_rejects_dict_shaped_evidence():
    replace = {"replaceText": {"text": TITLE_TEXT}}
    assert _already_applied(lambda: f"a {TITLE_TEXT} b", replace) is False


def test_already_applied_rejects_missing_and_empty_evidence():
    assert _already_applied(lambda: TITLE_TEXT, {}) is False
    assert _already_applied(lambda: TITLE_TEXT, {"replaceText": ""}) is False
    assert _already_applied(lambda: TITLE_TEXT, {"replaceText": None}) is False
    assert _already_applied(lambda: TITLE_TEXT, None) is False
    assert _already_applied(lambda: TITLE_TEXT, "not-a-dict") is False


def test_already_applied_rejects_unreadable_or_absent_content():
    def _boom():
        raise RuntimeError("read failed")

    assert _already_applied(_boom, _replace(TITLE_TEXT)) is False
    assert _already_applied(lambda: None, _replace(TITLE_TEXT)) is False
    assert _already_applied(lambda: "", _replace(TITLE_TEXT)) is False
    assert _already_applied(lambda: "unrelated", _replace(TITLE_TEXT)) is False
